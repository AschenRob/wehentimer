export interface WeightReference {
  p3: number
  p50: number
  p97: number
}

const MS_PER_DAY = 86_400_000

/** Lineare Interpolation (P3/P50/P97) im Alter zum Zeitpunkt; null außerhalb der Tabelle. */
export function interpolateWhoRows(
  rows: readonly WhoReferenceRow[],
  birth: Date,
  timestamp: number,
  digits: number,
): WeightReference | null {
  const age = (timestamp - birth.getTime()) / MS_PER_DAY
  if (age < 0 || age > rows[rows.length - 1][0]) return null
  const factor = 10 ** digits
  const round = (v: number) => Math.round(v * factor) / factor
  const upper = rows.findIndex((r) => r[0] >= age)
  if (upper <= 0) return { p3: rows[0][1], p50: rows[0][2], p97: rows[0][3] }
  const [d0, a0, b0, c0] = rows[upper - 1]
  const [d1, a1, b1, c1] = rows[upper]
  const f = (age - d0) / (d1 - d0)
  return {
    p3: round(a0 + (a1 - a0) * f),
    p50: round(b0 + (b1 - b0) * f),
    p97: round(c0 + (c1 - c0) * f),
  }
}

/** Normbereich (P3/P50/P97) zum Zeitpunkt; null außerhalb 0-24 Monate oder ohne Geschlecht. */
export function whoReferenceAt(
  gender: 'female' | 'male' | '',
  birth: Date,
  timestamp: number,
): WeightReference | null {
  if (!gender) return null
  return interpolateWhoRows(WHO_WEIGHT_FOR_AGE[gender === 'female' ? 'girls' : 'boys'], birth, timestamp, 0)
}