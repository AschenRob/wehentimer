/** Normbereich (P3/P50/P97) in cm zum Zeitpunkt; null außerhalb 0-24 Monate oder ohne Geschlecht. */
export function whoHeightReferenceAt(
  gender: 'female' | 'male' | '',
  birth: Date,
  timestamp: number,
): HeightReference | null {
  if (!gender) return null
  return interpolateWhoRows(WHO_LENGTH_FOR_AGE[gender === 'female' ? 'girls' : 'boys'], birth, timestamp, 1)
}
